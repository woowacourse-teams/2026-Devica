// 상태 코드가 없는 실패와 있는 실패는 원인이 전혀 다르다.
// 504 는 패킷이 버려졌다는 뜻이고 502 는 대상에 닿았다는 뜻이라, 화면에 함께 찍는 소요 시간과 보면 갈린다.
export function diagnose(status: number | null): string {
  if (status === null) {
    return '응답을 받지 못했습니다. 이 화면이 떴으므로 프론트엔드 서버는 살아 있습니다. 요청을 백엔드로 넘기는 경로가 설정돼 있는지 확인하세요.';
  }

  switch (status) {
    case 502:
      return '대상에는 닿았지만 백엔드가 응답하지 않습니다. 백엔드 컨테이너가 떠 있는지 확인하세요.';
    case 503:
      return '백엔드는 떠 있지만 구성 요소 하나가 준비되지 않았습니다. 대개 데이터베이스 연결입니다.';
    case 504:
      return '대상에 닿지 못했습니다. 방화벽·보안 그룹, 인스턴스 상태, 프록시 대상 주소 중 하나이며 셋은 이 화면에서 구분되지 않습니다. 콘솔에서 확인해야 합니다.';
    case 404:
      return '경로를 찾지 못했습니다. 프록시가 경로를 잘못 넘기고 있거나 요청한 자원이 없습니다.';
    default:
      return status >= 500
        ? '백엔드가 예외를 던졌습니다. 위 응답의 code 를 백엔드 로그와 대조하세요.'
        : '예상하지 못한 응답입니다.';
  }
}
